// Builds module.js for "Solpass jämför bostäder" from the demo's own home comparison code (index.html), so the numbers are
// the demo's. The demo code runs unchanged inside a small wrapper that gives it $, $$, state and a lead sender for HubSpot.
// Usage: node build-jamfor-js.js <index.html> ../modules/solpass-jamfor.module/module.js
const fs = require("fs");
const [demo, out] = process.argv.slice(2);
const src = fs.readFileSync(demo, "utf8");
const between = (a, b) => { const i = src.indexOf(a), j = src.indexOf(b, i); if (i < 0 || j < 0) throw new Error("marker not found: " + a); return src.slice(i, j); };
const one = re => { const m = src.match(re); if (!m) throw new Error("not found: " + re); return m[0]; };

const homeCode = between("/* ---------- home calculator (model ported", "function renderBostad(");
const picks = between("function pickHtml(", "const WHEN_OPTS");
const rate = one(/const RATE\s*=\s*[\d.]+;/);
const eur = one(/const eur = n => [^\n]+/);
const validEmail = one(/const validEmail = [^\n]+/);
const esc = one(/function esc\(s\)\{[^\n]+/);
const toast = one(/function toast\(msg\)\{[^\n]+/);

const js = `/* Generated by hubspot/site/build-jamfor-js.js from the demo's index.html. Do not edit by hand. */
(function(){
  var root = document.querySelector(".dv[data-jamfor]");
  if(!root || root.getAttribute("data-ready")) return;
  root.setAttribute("data-ready", "1");
  const $ = s => root.querySelector(s), $$ = s => Array.prototype.slice.call(root.querySelectorAll(s));
  const state = { email: "" };
  const profile = () => ({});
  const rememberEmail = e => { state.email = e; };
  ${rate}
  ${eur}
  ${validEmail}
  ${esc}
  ${toast.replace("document.body.appendChild", "root.appendChild")}
  let nlFlag = false;
  root.addEventListener("submit", e => { nlFlag = !!(e.target.querySelector && e.target.querySelector("[data-nl]:checked")); }, true);
  // the demo saved leads in its own table; here they go to the hidden HubSpot form, like the calculators
  async function saveLead(row){
    const portal = root.getAttribute("data-portal"), form = root.getAttribute("data-form");
    const nl = nlFlag; nlFlag = false;
    if(!portal || !form) return true;
    const when = (row.message || "").match(/köper (inom 6 månader|6–12 månader|om mer än ett år)/i);
    const homes = (row.calc && row.calc.homes || []).map(h => (h.name || "Bostad") + ": " + eur(h.price) + ", kontant " + eur(h.cash) + ", " + eur(Math.min(h.monthlyBonified, h.monthlyPlain)) + "/mån").join("; ");
    const props = {
      email: row.email, solpass_kalla: "kalkyl-bostad", solpass_bostad: "kopa",
      solpass_partnerbehov: (row.partner || "").split(",").map(p => p === "lawyer" ? "advokat" : "bank").filter((p, i, a) => a.indexOf(p) === i).join(";"),
      solpass_koptidpunkt: when ? { "inom 6 månader": "6m", "6–12 månader": "12m", "om mer än ett år": "senare" }[when[1].toLowerCase()] : "",
      solpass_kalkyl: ["Namn: " + row.name, row.phone ? "Telefon: " + row.phone : "", row.message || "", homes].filter(Boolean).join("\\n")
    };
    const fields = Object.keys(props).filter(k => props[k]).map(k => ({ name: k, value: String(props[k]) }));
    const context = { pageUri: location.href, pageName: document.title };
    const tk = document.cookie.match(/(?:^|;\\s*)hubspotutk=([^;]+)/); if(tk) context.hutk = decodeURIComponent(tk[1]);
    const body = { fields, context };
    const sub = root.getAttribute("data-nl");
    if(nl && sub) body.legalConsentOptions = { consent: { consentToProcess: true, text: root.getAttribute("data-consent") || "", communications: [{ value: true, subscriptionTypeId: Number(sub), text: "Flyttbrevet" }] } };
    try{
      const r = await fetch("https://api.hsforms.com/submissions/v3/integration/submit/" + encodeURIComponent(portal) + "/" + encodeURIComponent(form), { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) });
      return r.ok;
    }catch(e){ return false; }
  }
  ${picks.trim()}

  /* ---------- from the demo ---------- */
${homeCode}
  /* ---------- start ---------- */
  renderBuyer(); renderHomes(); renderHomeResults(); renderBankTable();
  // "Lägg till i jämförelsen" in the housing cost module above
  document.addEventListener("solpass:add-home", e => {
    if(home.homes.length >= 6){ toast("Jämförelsen har redan sex bostäder."); return; }
    home.homes.push(Object.assign({ id: newId(), name: "" }, e.detail));
    saveHome(); renderHomes(); renderHomeResults(); toast("Bostaden ligger nu i jämförelsen nedanför.");
  });
})();
`;
fs.writeFileSync(out, js);
console.log("wrote", out, js.length, "bytes");
