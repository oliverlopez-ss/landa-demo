// Scopes the demo's stylesheet (index.html) to ".dv", the root of the "Solpass vy" module, so demo views keep their exact look
// inside the HubSpot template. Light theme only, like the template. Header, footer and landing rules are dropped.
// Usage: NODE_PATH=<dir with postcss> node build-vy-css.js <index.html> ../modules/solpass-vy.module/module.css
const fs = require("fs"), postcss = require("postcss");
const [demo, out] = process.argv.slice(2);
const css = fs.readFileSync(demo, "utf8").match(/<style>([\s\S]*?)<\/style>/)[1];
const root = postcss.parse(css);
const DROP = /(^|[\s,>+~])(header\.site|footer\.site|\.hero|\.preview|\.ptask|\.facts|\.mainnav|\.dd|\.mm|\.ms\b|\.ml\b|\.scrim|\.burger|\.head-cta|#plusBadge|body\.on-landing|body\.menu-open|body\.nav-open|body::before|\.logo)/;
root.walkAtRules(at => {
  if (at.name === "media" && /prefers-color-scheme:\s*dark/.test(at.params)) at.remove();
});
root.walkRules(rule => {
  if (rule.parent.type === "atrule" && /keyframes/.test(rule.parent.name)) return;
  if (/\[data-theme="dark"\]/.test(rule.selector)) return rule.remove();
  const sels = rule.selectors.filter(s => !DROP.test(s));
  if (!sels.length) return rule.remove();
  rule.selectors = sels.map(s => {
    s = s.trim();
    if (s === ":root" || s === ":root:not([data-theme=\"light\"])" || s === "html" || s === "body") return ".dv";
    if (s === "*") return ".dv, .dv *";
    if (/^(html|body)\s/.test(s)) return ".dv " + s.replace(/^(html|body)\s+/, "");
    return ".dv " + s;
  });
});
root.walkAtRules(at => { if (at.name === "media" && !at.nodes.length) at.remove(); });
// Undo template rules that the demo does not have for the same class names; they come first so the demo's own rules win.
const RESET = `.dv .card{display:block;gap:normal;align-content:normal}
.dv .note{margin-top:0;font-size:inherit;color:inherit;max-width:none}
.dv details.qa:first-of-type{border-top:0}
/* HubSpot forms placed where the demo had its own forms */
.dv .hsf{margin-top:4px}
.dv .hsf-wrap>.hsf:first-child{margin-top:0}
/* the document vault's checklist form sits on one line, like the demo's: e-mail and button side by side */
.dv #dvCap .hs-form{display:flex;flex-wrap:wrap;gap:8px;align-items:flex-start}
.dv #dvCap .hs-form>*{flex-basis:100%;order:2}
.dv #dvCap .hs-form .hs-email{flex:1 1 200px;order:0;margin:0}
.dv #dvCap .hs-form .hs-email>label{position:absolute;width:1px;height:1px;overflow:hidden;clip:rect(0 0 0 0)}
.dv #dvCap .hs-form .hs_submit{flex:0 0 auto;order:1}
.dv #dvCap .hs-form .hs_submit .actions{margin:0;padding:0}
`;
fs.writeFileSync(out, "/* Generated by build-vy-css.js from the demo's index.html. Do not edit by hand. */\n" + RESET + root.toString().replace(/\n{3,}/g, "\n\n"));
console.log("wrote", out, fs.statSync(out).size, "bytes");
